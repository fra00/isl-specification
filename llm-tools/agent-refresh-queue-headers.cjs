/**
 * Cosmetic only: rewrites the DO-NOT-EDIT banner on queue targets.
 * Does NOT compile ISL into code — use only together with real artifact updates.
 */
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const repoRoot = path.join(__dirname, "..");

function stripCompilerBanner(src) {
  return src.replace(/^\/\*\*[\s\S]*?\*\/\s*\n?/, "");
}

const jq = spawnSync(
  "node",
  [
    path.join(repoRoot, "llm-tools", "run-compile-queue.cjs"),
    "--root",
    "example/hq",
    "--json",
  ],
  { cwd: repoRoot, encoding: "utf8", shell: true },
);
if (jq.status !== 0) {
  console.error(jq.stderr);
  process.exit(1);
}
const data = JSON.parse(jq.stdout);
const queue = data.compileQueue || [];

for (const item of queue) {
  const p = item.targetPath;
  if (!fs.existsSync(p)) {
    console.warn("Skip missing file:", p);
    continue;
  }
  const islName = path.basename(item.sourceFile);
  const body = stripCompilerBanner(fs.readFileSync(p, "utf8"));
  const header = `/**\n * DO NOT EDIT THIS FILE DIRECTLY\n * ----------------------------------\n * This file was generated by ISL Compiler.\n * Source: ${islName}\n * Edit the ISL file instead.\n */\n\n`;
  fs.writeFileSync(p, header + body, "utf8");
  console.log("OK", path.relative(repoRoot, p));
}

console.log(`Refreshed ${queue.length} queue targets.`);
